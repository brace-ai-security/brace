"""AP10: base images not pinned to a digest, and the Dockerfile reader."""

import pytest
from support import AGENT, found, rules, write

from open_agent_security.model import Document, SourceFile
from open_agent_security.parse.dockerfile import Dockerfile, is_dockerfile


def images(text: str) -> list[str]:
    doc = Document(SourceFile("Dockerfile", "repo", text))
    Dockerfile().parse(doc.source, doc)
    return [i.ref for i in doc.images]


def test_dockerfile_inline_ignore_after_blank_line(tmp_path):
    write(tmp_path, ".mcp.json", AGENT)
    write(tmp_path, "Dockerfile", "ARG X=1\n\nFROM python:3.12  # open-agent-security: ignore\n")
    assert rules(tmp_path) == []


def test_dockerfile_variants_and_templates(tmp_path):
    write(tmp_path, ".mcp.json", AGENT)
    write(tmp_path, "Containerfile.dev", "FROM fedora:40\n")
    write(tmp_path, "agent.dockerfile", "FROM node:22\n")
    write(tmp_path, "Dockerfile.j2", "FROM {{ base_image }}\n")
    assert rules(tmp_path) == ["AP10", "AP10"]


def test_unpinned_image_only_reported_in_agent_repos(tmp_path):
    write(tmp_path, "Dockerfile", "FROM python:3.12\n")
    assert rules(tmp_path) == []
    write(tmp_path, "app.py", "from claude_agent_sdk import query\n")
    assert rules(tmp_path) == ["AP10"]


def test_dockerfile_name_source_files_and_continuations(tmp_path):
    write(tmp_path, ".mcp.json", AGENT)
    write(tmp_path, "tools/dockerfile_gen.py", "from os import path\nfrom agents import x\n")
    write(tmp_path, "Dockerfile", 'FROM python@sha256:abc\nRUN psql -c "SELECT * \\\nFROM users"\n')
    assert rules(tmp_path) == []


def test_autogenerated_is_not_an_agent_signal(tmp_path):
    write(tmp_path, "gen.py", "# This file is autogenerated\n")
    write(tmp_path, "Dockerfile", "FROM python:3.12\n")
    assert rules(tmp_path) == []


def test_dockerfile_heredoc(tmp_path):
    write(tmp_path, ".mcp.json", AGENT)
    write(tmp_path, "Dockerfile", "FROM python@sha256:abc\nRUN psql <<EOF\nSELECT 1\nFROM t\nEOF\n")
    assert rules(tmp_path) == []


@pytest.mark.parametrize("text,expected", [
    ('FROM a\nRUN cat <<<"str"\nFROM b\n', ["a", "b"]),
    ('FROM a\nRUN echo "a << b"\nFROM b\n', ["a", "b"]),
    ("FROM a\nENV X=<<EOF\nFROM b\n", ["a", "b"]),
    ("FROM a\nRUN <<EOF\nFROM fake\nEOF\nFROM b\n", ["a", "b"]),
    ("FROM a\nCOPY <<-'EOT' /x\nFROM fake\nEOT\nFROM b\n", ["a", "b"]),
    ("FROM a\nRUN <<NEVER\nFROM b\n", ["a", "b"]),
])
def test_dockerfile_heredocs(text, expected):
    assert images(text) == expected


@pytest.mark.parametrize("name,expected", [
    ("Dockerfile", True), ("Containerfile", True), ("Dockerfile.dev", True), ("api.dockerfile", True),
    ("x.containerfile", True), ("dockerfile-notes.txt", False), ("Dockerfile.txt", False),
    ("Dockerfile.md", False), ("dockerfiles.py", False), ("Dockerfile.sh", False)])
def test_dockerfile_names(name, expected):
    assert is_dockerfile(name.lower()) is expected


def test_notes_file_is_not_a_dockerfile(tmp_path):
    write(tmp_path, ".mcp.json", "{}\n")
    write(tmp_path, "dockerfile-notes.txt", "FROM the notes, we learned a lot\n")
    assert rules(tmp_path) == []


def test_dockerfile_comment_lines_do_not_continue(tmp_path):
    write(tmp_path, ".mcp.json", "{}\n")
    write(tmp_path, "Dockerfile", "# build image \\\nFROM ubuntu:latest\n")
    assert found(tmp_path) == [("AP10", "FROM ubuntu:latest")]


def test_dockerfile_escape_directive(tmp_path):
    write(tmp_path, ".mcp.json", "{}\n")
    write(tmp_path, "Dockerfile", "# escape=`\nFROM node:20 AS build\nRUN echo hi `\n    FROM nothing\n"
                                  "RUN dir C:\\ \nFROM ubuntu:latest\n")
    assert found(tmp_path) == [("AP10", "FROM node:20"), ("AP10", "FROM ubuntu:latest")]


def test_autogen_sh_is_not_an_agent_signal(tmp_path):
    write(tmp_path, "build.sh", "./autogen.sh && make\n")
    write(tmp_path, "Dockerfile", "FROM ubuntu:latest\n")
    assert rules(tmp_path) == []
    write(tmp_path, "agent.py", "import autogen\n")
    assert rules(tmp_path) == ["AP10"]
