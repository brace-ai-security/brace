#!/usr/bin/env python3
"""Build the skills' reference files from the BRACE source documents.

Sources: CHECKLIST.md (requirements), CHECKLIST-VERIFICATION.md (recipes),
ROLES.md (Lead and Shares), and skills/brace-review/heuristics/<aspect>.yaml.

Outputs:
  skills/brace-review/references/<aspect>.md
  skills/brace-tests/references/<aspect>.md
  skills/brace-review/references/checks.json (must_show checks, read by validate_findings.py)

Run with --check to fail (exit 1) when the outputs are out of date.
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent / "brace-review/scripts"))
from review_coverage import spec as coverage_spec


import yaml

ROOT = Path(__file__).resolve().parent.parent
ASPECTS = {
    "B": ("build-time", "B — Build-time"),
    "R": ("run-time", "R — Run-time"),
    "A": ("agent", "A — Agent"),
    "C": ("configuration", "C — Configuration"),
    "E": ("ecosystem", "E — Ecosystem"),
}
HEAD = re.compile(r"^- \[ \] \*\*([BRACE]\d\d) · (G\d) · ([^ ]+) — (.+?)\.\*\*\s?(.*)$")
GENERATED = "<!-- Generated by skills/gen_references.py from CHECKLIST.md, CHECKLIST-VERIFICATION.md, ROLES.md, and heuristics. Do not edit by hand. -->"


def parse_checklist():
    lines = (ROOT / "CHECKLIST.md").read_text().splitlines()
    items, cur = {}, None
    for line in lines:
        m = HEAD.match(line)
        if m:
            iid, gate, controls, title, rest = m.groups()
            cur = items[iid] = {"gate": gate, "controls": controls, "title": title, "text": [rest]}
            continue
        if cur is None:
            continue
        if line.startswith(("#", "**Evidence to attach")) or line.startswith("- [ ]"):
            cur = None
            continue
        cur["text"].append(line)
    for it in items.values():
        text = "\n".join(it["text"]).strip()
        it["text"] = re.sub(r"\n{3,}", "\n\n", text).replace("**", "") if text else ""
        it["requirement"] = it["text"].split("\n\n")[0].strip()
    return items


def parse_recipes():
    rows = {}
    for line in (ROOT / "CHECKLIST-VERIFICATION.md").read_text().splitlines():
        m = re.match(r"^\| ([BRACE]\d\d) \| (.+) \| (.+) \|$", line)
        if m:
            rows[m.group(1)] = (m.group(2).strip(), m.group(3).strip())
    return rows


def parse_roles():
    roles = {}
    for line in (ROOT / "ROLES.md").read_text().splitlines():
        m = re.match(r"^\| ([BRACE]\d\d) \| G\d \| .+? \| \*\*(.+?)\*\* \| (.+) \|$", line)
        if m:
            roles[m.group(1)] = (m.group(2), m.group(3).strip())
    return roles


def load_heuristics(aspect):
    path = ROOT / "skills" / "brace-review" / "heuristics" / f"{aspect}.yaml"
    return yaml.safe_load(path.read_text()) or {} if path.exists() else {}


def bullets(values):
    return "\n".join(f"- {v}" for v in values or []) or "- (none listed)"


def render(letter, items, recipes, roles, with_heuristics, must_show=None, not_covered=None, na_when=None):
    must_show = {} if must_show is None else must_show
    not_covered = {} if not_covered is None else not_covered
    na_when = {} if na_when is None else na_when
    slug, name = ASPECTS[letter]
    heur = load_heuristics(slug) if with_heuristics else {}
    ids = sorted(i for i in items if i[0] == letter)
    if with_heuristics:
        intro = ("Use this file to rate each item from the code and configuration. "
                 "The requirement is the checklist text. The heuristics say what to look for. "
                 "Ratings: likely_pass, gap, needs_evidence, or na_candidate. Never rate pass.")
    else:
        intro = ("Use this file to write tests and drills for each item. "
                 "Each recipe gives the procedure, the expected result, and the evidence to keep.")
    out = [GENERATED, "", f"# {name}", "", intro, ""]
    for iid in ids:
        it = items[iid]
        lead, shares = roles.get(iid, ("(see ROLES.md)", "—"))
        proc, evid = recipes.get(iid, ("(no recipe found)", ""))
        out += [f"## {iid} · {it['gate']} · {it['controls']} — {it['title']}", "",
                f"**Lead:** {lead}. **Shares:** {shares}.", ""]
        if with_heuristics:
            out += ["### Requirement", "", it["text"], ""]
        out += ["### Verification recipe", "", proc, "", f"**Evidence to keep:** {evid}", ""]
        if with_heuristics:
            h = heur.get(iid)
            if not h:
                raise SystemExit(f"Missing heuristics for {iid} in heuristics/{slug}.yaml")
            na_when[iid] = h.get("na_when", "never")
            provable = h.get("provable_from_code")
            # YAML 1.1 reads unquoted yes/no as booleans.
            provable = {True: "yes", False: "no"}.get(provable, provable)
            if provable not in ("yes", "partly", "no"):
                raise SystemExit(f"{iid}: provable_from_code must be yes, partly, or no")
            checks = h.get("must_show")
            if checks is None:
                raise SystemExit(f"{iid}: must_show is missing (use [] if code can't show the requirement)")
            for c in checks:
                if not str(c.get("id", "")).startswith(iid + ".") or not c.get("check"):
                    raise SystemExit(f"{iid}: each must_show entry needs an id like {iid}.1 and a check")
            must_show[iid] = [{"id": c["id"], "check": c["check"], **coverage_spec(c["id"]), **({"verify": c["verify"]} if c.get("verify") else {}),
                               **({"doc_ok": True} if c.get("doc_ok") else {})} for c in checks]
            if checks:
                ms = "\n".join(f"- **{c['id']}** {c['check']}" + (" *(A document can show this.)*" if c.get("doc_ok") else "")
                               + (f"\n  - *How to verify:* {c['verify']}" if c.get("verify") else "") for c in checks)
                ms_intro = "Rate likely_pass only if every check below is true, with a file and line for each:"
            else:
                ms = "- (none) Code can't show this item. Don't rate it likely_pass; use needs_evidence, gap, or na_candidate."
                ms_intro = "Checks for likely_pass:"
            out += ["### Checks for likely_pass", "", ms_intro, "", ms, ""]
            nc = h.get("not_covered") or []
            not_covered[iid] = [{"problem": n["problem"], "owner": n["owner"]} for n in nc]
            if nc:
                out += ["### Not covered here", "",
                        "File these problems under their owning item, not this one, unless this item's own requirement is also broken:", "",
                        "\n".join(f"- {n['problem']} → **{n['owner']}**" for n in nc), ""]
            out += ["### Heuristics", "",
                    f"**Provable from code:** {provable}", "",
                    "**Look for:**", bullets(h.get("look_for")), "",
                    "**Red flags:**", bullets(h.get("red_flags")), "",
                    "**Where to look:**", bullets(h.get("where_to_look")), "",
                    f"**Needs runtime evidence:** {h.get('needs_runtime_evidence', '')}", "",
                    f"**N/A when:** {h.get('na_when', 'never')}", ""]
    return "\n".join(out).rstrip() + "\n"


def main():
    check = "--check" in sys.argv
    items, recipes, roles = parse_checklist(), parse_recipes(), parse_roles()
    if len(items) != 53 or len(recipes) != 53 or len(roles) != 53:
        raise SystemExit(f"Expected 53 items; found checklist={len(items)} recipes={len(recipes)} roles={len(roles)}")
    stale, must_show, not_covered, na_when = [], {}, {}, {}
    outputs = []
    for skill, with_h in (("brace-review", True), ("brace-tests", False)):
        for letter, (slug, _) in ASPECTS.items():
            path = ROOT / "skills" / skill / "references" / f"{slug}.md"
            outputs.append((path, render(letter, items, recipes, roles, with_h, must_show, not_covered, na_when)))
    role_key = {"Agent team": "agent_team", "Operations": "operations", "Security": "security",
                "Infrastructure": "infrastructure", "Governance": "governance", "Business owner": "business_owner",
                "Data and privacy": "data_privacy", "Model team": "model_team", "Vendors": "vendors",
                "Independent audit": "independent_audit"}
    table = {iid: {"gate": items[iid]["gate"], "title": items[iid]["title"],
                   "lead_role": role_key[roles[iid][0]], "requirement": items[iid]["requirement"],
                   "not_covered": not_covered.get(iid, []), "na_when": na_when[iid], "checks": must_show[iid]}
             for iid in sorted(must_show)}
    outputs.append((ROOT / "skills" / "brace-review" / "references" / "checks.json",
                    json.dumps(table, indent=1) + "\n"))
    for path, text in outputs:
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if check and stale:
        print("Out of date; run python skills/gen_references.py:\n  " + "\n  ".join(stale))
        sys.exit(1)
    print("References up to date." if check else "References written.")


if __name__ == "__main__":
    main()
